import type { Integration as OperatorIntegration } from "@checkdrop/core";
import type { IntegrationRecord } from "@checkdrop/db";
import { embedSnippet, readInstanceConfig } from "./instance-config.js";

export function serializeIntegration(
  record: IntegrationRecord,
  apiUrl: string = readInstanceConfig().publicApiUrl,
): OperatorIntegration {
  const siteKey = `cdp_site_${record.id}`;
  return {
    object: "integration",
    id: record.id,
    name: record.name,
    client_name: record.clientName,
    environment: record.environment,
    form_url: record.formUrl,
    state: record.state,
    config_version: record.configVersion,
    site_key: siteKey,
    embed_script: embedSnippet(apiUrl, siteKey),
    created_at: record.createdAt.toISOString(),
    updated_at: record.updatedAt.toISOString(),
    fields: record.fields.map((field) => ({
      id: field.id,
      selector: field.sourceSelector,
      label: field.sourceLabel,
      name: field.sourceName,
      canonical_field: field.canonicalField,
      context: field.context,
      condition_key: field.conditionKey,
      required: field.required,
      require_complete_name: field.requireCompleteName ?? false,
      require_domestic_address: field.requireDomesticAddress ?? false,
      require_valid_phone: field.requireValidPhone ?? false,
      fill_village_street: field.fillVillageStreet ?? false,
      submit_selector: field.submitSelector ?? null,
      validation_mode: field.validationMode,
      validation_trigger: field.validationTrigger,
      confidence: field.confidence,
      detected: field.detected,
    })),
    forms: record.forms.map((form) => ({
      id: form.id,
      name: form.name,
      form_url: form.formUrl,
      match_mode: form.matchMode,
      path_pattern: form.pathPattern,
      root_selector: form.rootSelector ?? "body",
      state: form.state,
      config_version: form.configVersion,
      is_default: form.isDefault,
      created_at: form.createdAt.toISOString(),
      updated_at: form.updatedAt.toISOString(),
      fields: form.fields.map((field) => ({
        id: field.id,
        selector: field.sourceSelector,
        label: field.sourceLabel,
        name: field.sourceName,
        canonical_field: field.canonicalField,
        context: field.context,
        condition_key: field.conditionKey,
        required: field.required,
        require_complete_name: field.requireCompleteName ?? false,
        require_domestic_address: field.requireDomesticAddress ?? false,
        require_valid_phone: field.requireValidPhone ?? false,
        fill_village_street: field.fillVillageStreet ?? false,
        submit_selector: field.submitSelector ?? null,
        validation_mode: field.validationMode,
        validation_trigger: field.validationTrigger,
        confidence: field.confidence,
        detected: field.detected,
      })),
    })),
    api_keys: record.apiKeys.map((key) => ({
      id: key.id,
      name: key.name,
      key_prefix: key.keyPrefix,
      environment: key.environment,
      state: key.state,
      created_at: key.createdAt.toISOString(),
      last_used_at: key.lastUsedAt?.toISOString() ?? null,
      revoked_at: key.revokedAt?.toISOString() ?? null,
    })),
    activity: {
      last_key_used_at: record.activity.lastKeyUsedAt?.toISOString() ?? null,
      observation_count_24h: record.activity.observationCount24h,
      last_observation_at: record.activity.lastObservationAt?.toISOString() ?? null,
    },
  };
}
